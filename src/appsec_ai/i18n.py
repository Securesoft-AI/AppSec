# Títulos y mensajes con partes variables (nombre de la herramienta, del secreto...).
_DYNAMIC_EN = [
    (re.compile(r"^Secreto expuesto: (.*)$"), r"Exposed secret: \1"),
    (re.compile(r"^Salida del LLM ejecutada como código o comando \((.*)\)$"), r"LLM output executed as code or command (\1)"),
    (re.compile(r"^Herramienta de agente '(.*)' con acciones peligrosas$"), r"Agent tool '\1' with dangerous actions"),
    (re.compile(r"^Herramienta de servidor MCP '(.*)' con acciones peligrosas$"), r"MCP server tool '\1' with dangerous actions"),
    (re.compile(r"^Recurso: (.*)$"), r"Resource: \1"),
]
_EXTRA_EN = (re.compile(r"Operaciones sensibles detectadas: (.*)$"), r"Sensitive operations detected: \1")


def localize(f: Finding, lang: str) -> tuple[str, str]:
    """(título, mensaje) del hallazgo en el idioma pedido."""
    if norm(lang) == "es":
        return f.title, f.message
    title, message = f.title, f.message
    base = RULES_EN.get(f.rule_id)
    dynamic = next((rx.sub(repl, title) for rx, repl in _DYNAMIC_EN if rx.match(title)), None)
    if dynamic:
        title = dynamic
    elif base:
        title = base[0]
    if base:
        extra = _EXTRA_EN[0].search(message)
        message = base[1] + (" " + _EXTRA_EN[0].sub(_EXTRA_EN[1], extra.group(0)) if extra else "")
    else:
        message = next((rx.sub(repl, message) for rx, repl in _DYNAMIC_EN if rx.match(message)), message)
    return title, message


